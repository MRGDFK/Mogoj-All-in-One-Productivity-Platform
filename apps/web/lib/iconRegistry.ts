export function isLucideIconName(value: string): value is keyof typeof ICON_LIBRARY {
  return Object.prototype.hasOwnProperty.call(ICON_LIBRARY, value);
}

export function isImageIcon(value: string): boolean {
  return value.startsWith("http://") || value.startsWith("https://") || value.startsWith("data:");
}

